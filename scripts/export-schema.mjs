// Writes the schema used at boot to supabase/migrations so it can also be applied
// with the Supabase CLI (`supabase db push`) or pasted into the SQL editor.
import fs from 'node:fs';
import { SCHEMA } from '../src/server/db/schema.js';

const out = new URL('../supabase/migrations/0001_init.sql', import.meta.url);
fs.writeFileSync(out, `-- HCM Lite schema (generated by npm run db:sql from src/server/db/schema.js)\n${SCHEMA.trim()}\n`);
console.log('wrote', out.pathname);
