import PDFDocument from 'pdfkit';

const money = (n, cur) => `${cur} ${Number(n || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

// Renders a payslip to a PDF Buffer.
export function renderPayslipPdf(p, settings) {
  const cur = settings.currency || 'PKR';
  const doc = new PDFDocument({ size: 'A4', margin: 48, info: { Title: `Payslip ${p.label} - ${p.name}` } });
  const chunks = [];
  doc.on('data', (c) => chunks.push(c));
  const done = new Promise((resolve, reject) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });

  doc.rect(0, 0, doc.page.width, 92).fill('#1f2a44');
  doc.fill('#ffffff').fontSize(20).font('Helvetica-Bold').text(settings.company_name || 'Company', 48, 30);
  doc.fontSize(11).font('Helvetica').text(`Payslip - ${p.label}`, 48, 58);
  doc.fontSize(9).text(p.run_status === 'finalized' ? 'FINAL' : 'DRAFT', doc.page.width - 120, 36, { width: 72, align: 'right' });

  doc.fontSize(10);
  let y = 116;
  const field = (label, value, x) => {
    doc.font('Helvetica').fill('#6b7280').text(label, x, y);
    doc.font('Helvetica-Bold').fill('#111827').text(value ?? '-', x + 100, y);
  };
  field('Employee', p.name, 48);
  field('Code', p.code, 310);
  y += 18;
  field('Department', p.department, 48);
  field('Designation', p.designation, 310);
  y += 18;
  field('Working days', String(p.working_days), 48);
  field('Days employed', String(p.employed_days), 310);
  y += 30;

  const table = (title, lines, x) => {
    let ty = y;
    doc.rect(x, ty, 240, 22).fill('#eef2f7');
    doc.fill('#1f2a44').font('Helvetica-Bold').text(title, x + 10, ty + 7);
    ty += 28;
    for (const [label, value] of lines) {
      doc.font('Helvetica').fill('#374151').text(label, x + 10, ty, { width: 140 });
      doc.font('Helvetica').fill('#111827').text(value, x + 120, ty, { width: 110, align: 'right' });
      ty += 18;
    }
    return ty;
  };
  const left = table(
    'Earnings',
    [
      ['Basic', money(p.basic, cur)],
      ['House rent (HRA)', money(p.hra, cur)],
      ['Medical', money(p.medical, cur)],
      ['Other allowance', money(p.other_allowance, cur)],
      ['Monthly gross', money(p.monthly_gross, cur)],
      ['Gross for period', money(p.gross, cur)],
    ],
    48,
  );
  const right = table(
    'Deductions',
    [
      ['Absent days', String(p.absent_days)],
      ['Unpaid leave days', String(p.unpaid_leave_days)],
      ['Half days (x 0.5)', String(p.half_days)],
      ['Late penalty days', String(p.late_penalty_days)],
      ['Attendance deduction', money(p.deductions, cur)],
      ['Income tax', money(p.tax, cur)],
    ],
    307,
  );
  y = Math.max(left, right) + 16;
  doc.rect(48, y, 499, 40).fill('#0f9d7a');
  doc.fill('#ffffff').font('Helvetica-Bold').fontSize(13).text('Net pay', 62, y + 13);
  doc.text(money(p.net, cur), 300, y + 13, { width: 233, align: 'right' });
  y += 64;
  doc.fill('#6b7280').font('Helvetica').fontSize(8.5);
  doc.text(
    `Per-day rate ${money(p.per_day, cur)} = monthly gross / ${p.working_days} working days. ` +
      `Tax uses the illustrative slab on annual gross of ${money(p.taxable_annual, cur)}. ` +
      'Generated by HCM Lite from attendance and leave records.',
    48,
    y,
    { width: 499 },
  );
  doc.end();
  return done;
}
